#!/usr/bin/env python3
"""
test_transformed_ir_inspection.py

Automated test that inspects transformed LLVM IR generated by MemoryGuardPass.
Verifies:
  1. Negative / unsupported cases receive 0 `mg_check_access` calls:
     - IntToPtr / PtrToInt
     - AddrSpaceCast
     - Unsupported constant expressions
     - Loads from unknown / external memory
     - Ambiguous PHI nodes (heap + stack + unknown)
     - Ambiguous Select instructions
     - Callee with conflicting call-site origins
     - Unresolved external callers
     - Indirect callers (address taken)
     - Indirect calls to allocators
     - Variadic allocator declarations
     - Non-C calling convention allocator calls
     - Atomic loads and stores
     - Atomic RMW and compare-exchange
     - Atomic fences
     - Scalable vector accesses
     - Non-default address space accesses
  2. Unsupported allocator calls are NOT rewritten to mg_intercept_*:
     - Indirect calls through function pointers
     - Variadic allocator calls
     - Non-C calling convention allocator calls
  3. Atomic instructions remain intact with exact ordering semantics.
  4. Supported positive baseline (test_pos_supported_heap_access) DOES receive
     exactly 2 `mg_check_access` calls and is rewritten to `mg_intercept_malloc`.
  5. The pass is idempotent: running `-passes=memoryguard,memoryguard` produces
     bit-for-bit identical LLVM IR with zero duplicate checks.
"""

import sys
import os
import subprocess
import re

def extract_function_bodies(ll_content):
    """
    Extracts a dictionary mapping function name -> function body IR string.
    """
    functions = {}
    current_fn = None
    current_lines = []

    for line in ll_content.splitlines():
        define_match = re.match(r"^define\s+.*@([a-zA-Z0-9_]+)\s*\(", line)
        if define_match:
            current_fn = define_match.group(1)
            current_lines = [line]
        elif current_fn is not None:
            current_lines.append(line)
            if line.strip() == "}":
                functions[current_fn] = "\n".join(current_lines)
                current_fn = None
                current_lines = []

    return functions

def main():
    if len(sys.argv) < 4:
        print(f"Usage: {sys.argv[0]} <opt_tool> <plugin_path> <input_ll_path>")
        sys.exit(1)

    opt_tool = sys.argv[1]
    plugin_path = sys.argv[2]
    input_ll = sys.argv[3]

    output_pass1 = "test_transformed_ir_pass1.ll"
    output_pass2 = "test_transformed_ir_pass2.ll"

    # Step 1: Run opt with single pass
    cmd1 = [
        opt_tool,
        f"-load-pass-plugin={plugin_path}",
        "-passes=memoryguard",
        "-S",
        input_ll,
        "-o",
        output_pass1
    ]
    print(f"[RUN] {' '.join(cmd1)}")
    res1 = subprocess.run(cmd1, capture_output=True, text=True)
    if res1.returncode != 0:
        print(f"[FAIL] opt execution failed:\nSTDOUT:\n{res1.stdout}\nSTDERR:\n{res1.stderr}")
        sys.exit(1)

    with open(output_pass1, "r") as f:
        ll_pass1 = f.read()

    fn_map = extract_function_bodies(ll_pass1)

    total_checks = 0
    passed_checks = 0

    def assert_test(cond, msg):
        nonlocal total_checks, passed_checks
        total_checks += 1
        if cond:
            passed_checks += 1
            print(f"  [PASS] {msg}")
        else:
            print(f"  [FAIL] {msg}")

    print("\n--- Inspecting Negative / Unsupported Scenarios ---")

    # 1. Unsupported pointer transformations
    fn = fn_map.get("test_neg_inttoptr_ptrtoint", "")
    assert_test("call void @mg_check_access" not in fn, "test_neg_inttoptr_ptrtoint has 0 check_access calls")

    fn = fn_map.get("test_neg_addrspace_conversion", "")
    assert_test("call void @mg_check_access" not in fn, "test_neg_addrspace_conversion has 0 check_access calls")

    fn = fn_map.get("test_neg_unsupported_expr", "")
    assert_test("call void @mg_check_access" not in fn, "test_neg_unsupported_expr has 0 check_access calls")

    fn = fn_map.get("test_neg_load_from_unknown_memory", "")
    assert_test("call void @mg_check_access" not in fn, "test_neg_load_from_unknown_memory has 0 check_access calls")

    # 2. Ambiguous pointer origins
    fn = fn_map.get("test_neg_phi_heap_stack_unknown", "")
    assert_test("call void @mg_check_access" not in fn, "test_neg_phi_heap_stack_unknown has 0 check_access calls")

    fn = fn_map.get("test_neg_select_conflicting", "")
    assert_test("call void @mg_check_access" not in fn, "test_neg_select_conflicting has 0 check_access calls")

    fn = fn_map.get("internal_callee_conflicting", "")
    assert_test("call void @mg_check_access" not in fn, "internal_callee_conflicting has 0 check_access calls")

    fn = fn_map.get("test_neg_unresolved_external_caller", "")
    assert_test("call void @mg_check_access" not in fn, "test_neg_unresolved_external_caller has 0 check_access calls")

    fn = fn_map.get("internal_callee_addr_taken", "")
    assert_test("call void @mg_check_access" not in fn, "internal_callee_addr_taken has 0 check_access calls")

    # 3. Unsupported call patterns
    fn = fn_map.get("test_neg_indirect_alloc_call", "")
    assert_test("call void @mg_check_access" not in fn, "test_neg_indirect_alloc_call has 0 check_access calls")
    assert_test("mg_intercept_malloc" not in fn, "test_neg_indirect_alloc_call was NOT rewritten to mg_intercept_malloc")
    assert_test("mg_intercept_free" not in fn, "test_neg_indirect_alloc_call was NOT rewritten to mg_intercept_free")

    fn = fn_map.get("test_neg_variadic_allocator", "")
    assert_test("call void @mg_check_access" not in fn, "test_neg_variadic_allocator has 0 check_access calls")
    assert_test("mg_intercept_malloc" not in fn, "test_neg_variadic_allocator was NOT rewritten to mg_intercept_malloc")

    fn = fn_map.get("test_neg_non_c_calling_convention", "")
    assert_test("call void @mg_check_access" not in fn, "test_neg_non_c_calling_convention has 0 check_access calls")
    assert_test("fastcc ptr @malloc" in fn, "test_neg_non_c_calling_convention preserves fastcc malloc call")

    # 4. Unsupported memory operations
    fn = fn_map.get("test_neg_atomic_load_store", "")
    assert_test("call void @mg_check_access" not in fn, "test_neg_atomic_load_store has 0 check_access calls")
    assert_test("store atomic i32 444, ptr %p release" in fn, "test_neg_atomic_load_store preserves release store")
    assert_test("load atomic i32, ptr %p acquire" in fn, "test_neg_atomic_load_store preserves acquire load")

    fn = fn_map.get("test_neg_atomic_rmw_cmpxchg", "")
    assert_test("call void @mg_check_access" not in fn, "test_neg_atomic_rmw_cmpxchg has 0 check_access calls")
    assert_test("atomicrmw add ptr %p, i32 10 seq_cst" in fn, "test_neg_atomic_rmw_cmpxchg preserves atomicrmw")
    assert_test("cmpxchg ptr %p, i32 10, i32 20 seq_cst seq_cst" in fn, "test_neg_atomic_rmw_cmpxchg preserves cmpxchg")

    fn = fn_map.get("test_neg_atomic_fence", "")
    assert_test("fence seq_cst" in fn and "fence release" in fn and "fence acquire" in fn,
                "test_neg_atomic_fence preserves all fence instructions")

    fn = fn_map.get("test_neg_scalable_vector", "")
    assert_test("call void @mg_check_access" not in fn, "test_neg_scalable_vector has 0 check_access calls")
    assert_test("<vscale x 4 x i32>" in fn, "test_neg_scalable_vector preserves scalable vector types")

    fn = fn_map.get("test_neg_non_default_addrspace", "")
    assert_test("call void @mg_check_access" not in fn, "test_neg_non_default_addrspace has 0 check_access calls")

    # 5. Positive baseline
    print("\n--- Inspecting Positive Baseline Scenario ---")
    pos_fn = fn_map.get("test_pos_supported_heap_access", "")
    check_count = pos_fn.count("call void @mg_check_access")
    assert_test(check_count == 2, f"test_pos_supported_heap_access has exactly 2 check_access calls (found {check_count})")
    assert_test("call ptr @mg_intercept_malloc" in pos_fn, "test_pos_supported_heap_access rewritten to mg_intercept_malloc")
    assert_test("call void @mg_intercept_free" in pos_fn, "test_pos_supported_heap_access rewritten to mg_intercept_free")

    # Step 2: Idempotence check with double pass
    print("\n--- Inspecting Pass Idempotence ---")
    cmd2 = [
        opt_tool,
        f"-load-pass-plugin={plugin_path}",
        "-passes=memoryguard,memoryguard",
        "-S",
        input_ll,
        "-o",
        output_pass2
    ]
    print(f"[RUN] {' '.join(cmd2)}")
    res2 = subprocess.run(cmd2, capture_output=True, text=True)
    if res2.returncode != 0:
        print(f"[FAIL] opt double pass failed:\n{res2.stderr}")
        sys.exit(1)

    with open(output_pass2, "r") as f:
        ll_pass2 = f.read()

    assert_test(ll_pass1 == ll_pass2, "Running pass twice produces identical IR (100% idempotent)")

    print(f"\n====================================================")
    print(f"Summary: {passed_checks} / {total_checks} assertions passed")
    print(f"====================================================")

    # Cleanup temporary files
    if os.path.exists(output_pass1):
        os.remove(output_pass1)
    if os.path.exists(output_pass2):
        os.remove(output_pass2)

    if passed_checks == total_checks:
        print("ALL IR INSPECTION ASSERTIONS PASSED!")
        sys.exit(0)
    else:
        print(f"FAILED: {total_checks - passed_checks} assertion(s) failed!")
        sys.exit(1)

if __name__ == "__main__":
    main()
